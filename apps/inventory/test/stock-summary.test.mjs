import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import test from 'node:test';
import { StockService } from '../dist/stock/stock.service.js';
import { stockSummaryQuerySchema } from '@jewelry/contracts';

const branchId = randomUUID();
const user = { id: randomUUID(), branches: [{ role: 'STAFF', branchId }] };
test('summary rejects missing scope and foreign branch before querying PostgreSQL', async () => {
  let queried = false;
  const service = new StockService({
    $queryRaw() {
      queried = true;
    },
  });
  await assert.rejects(
    service.summary(user, { branchId: randomUUID(), page: 1, pageSize: 20 }),
    (e) => e.status === 403 || e.statusCode === 403 || e.code === 'FORBIDDEN',
  );
  assert.equal(queried, false);
  assert.equal(stockSummaryQuerySchema.safeParse({ page: 1 }).success, false);
});

// Opt-in PostgreSQL test: temporary tables on one connection, always ROLLBACK.
// Runs the actual SQL generated by StockService; no mock of aggregate results.
test(
  'PostgreSQL summary: states, expiry, duplicates, branch, paging, receipt and sale',
  {
    skip: !process.env.STOCK_SUMMARY_TEST_URL,
  },
  async () => {
    const req = createRequire(import.meta.url);
    const pgReq = createRequire(req.resolve('@prisma/adapter-pg'));
    const { Client } = pgReq('pg');
    const client = new Client({ connectionString: process.env.STOCK_SUMMARY_TEST_URL });
    await client.connect();
    try {
      await client.query('BEGIN');
      for (const [name, columns] of Object.entries({
        Warehouse: 'id uuid, "branchId" uuid, name text, "isActive" bool',
        Category: 'id uuid, "isActive" bool',
        Product: 'id uuid, "categoryId" uuid, name text, "isActive" bool',
        Metal: 'id uuid, name text, "isActive" bool',
        MetalPrice: '"metalId" uuid, "effectiveFrom" timestamptz',
        ProductVariant:
          'id uuid, "productId" uuid, "metalId" uuid, sku text, name text, "isActive" bool',
        JewelryItem: 'id uuid, "warehouseId" uuid, "variantId" uuid, status text',
        StockReservation: 'id uuid, status text, "expiresAt" timestamptz',
        StockReservationItem: '"reservationId" uuid, "jewelryItemId" uuid, "isActive" bool',
        ExchangeHold: '"itemId" uuid, status text, "expiresAt" timestamptz',
      }))
        await client.query(`CREATE TEMP TABLE "${name}" (${columns}) ON COMMIT DROP`);
      const service = new StockService({
        async $queryRaw(query) {
          const result = await client.query(
            query.text.replaceAll('"inventory".', 'pg_temp.'),
            query.values,
          );
          return result.rows;
        },
      });
      const variant = randomUUID(),
        otherVariant = randomUUID(),
        warehouse = randomUUID();
      const foreignWarehouse = randomUUID(),
        foreignBranch = randomUUID();
      const category = randomUUID(),
        product = randomUUID(),
        metal = randomUUID();
      await client.query("INSERT INTO \"Warehouse\" VALUES ($1,$2,'A',true),($3,$4,'B',true)", [
        warehouse,
        branchId,
        foreignWarehouse,
        foreignBranch,
      ]);
      await client.query('INSERT INTO "Category" VALUES ($1,true)', [category]);
      await client.query('INSERT INTO "Product" VALUES ($1,$2,\'Nhẫn\',true)', [product, category]);
      await client.query('INSERT INTO "Metal" VALUES ($1,\'18K\',true)', [metal]);
      await client.query('INSERT INTO "MetalPrice" VALUES ($1,now())', [metal]);
      await client.query(
        "INSERT INTO \"ProductVariant\" VALUES ($1,$2,$3,'A','A',true),($4,$2,$3,'B','B',true)",
        [variant, product, metal, otherVariant],
      );
      const add = async (status, v = variant, w = warehouse) => {
        const id = randomUUID();
        await client.query('INSERT INTO "JewelryItem" VALUES ($1,$2,$3,$4)', [id, w, v, status]);
        return id;
      };
      const online = async (item, status, future, active = true) => {
        const id = randomUUID();
        await client.query(
          'INSERT INTO "StockReservation" VALUES ($1,$2,now()+($3::int * interval \'1 hour\'))',
          [id, status, future ? 1 : -1],
        );
        await client.query('INSERT INTO "StockReservationItem" VALUES ($1,$2,$3)', [
          id,
          item,
          active,
        ]);
      };
      const stock = await add('IN_STOCK');
      await add('IN_STOCK');
      const held = await add('RESERVED');
      await online(held, 'ACTIVE', true);
      await online(held, 'ACTIVE', true); // duplicate history cannot multiply the item
      const expired = await add('RESERVED');
      await online(expired, 'ACTIVE', false);
      const paid = await add('RESERVED');
      await online(paid, 'PAID_HELD', true);
      const exchange = await add('RESERVED');
      await client.query(
        "INSERT INTO \"ExchangeHold\" VALUES ($1,'PROTECTED',now()+interval '1 hour')",
        [exchange],
      );
      const expiredExchange = await add('RESERVED');
      await client.query(
        "INSERT INTO \"ExchangeHold\" VALUES ($1,'ACTIVE',now()-interval '1 hour')",
        [expiredExchange],
      );
      const inactive = await add('RESERVED');
      await online(inactive, 'ACTIVE', true, false);
      await add('SOLD');
      await add('PENDING_MELT');
      await add('IN_STOCK', variant, foreignWarehouse);
      await add('IN_STOCK', otherVariant);
      const query = { branchId, variantId: variant, page: 1, pageSize: 20 };
      let result = await service.summary(user, query);
      const counts = (r) =>
        ['total', 'available', 'reserved', 'sold', 'pendingMelt', 'other'].map((k) => r[k]);
      assert.deepEqual(counts(result.items[0]), [10, 2, 3, 1, 1, 3]);
      assert.equal(result.items[0].branchId, branchId);
      assert.equal(result.total, 1);
      await add('IN_STOCK');
      result = await service.summary(user, query);
      assert.deepEqual(counts(result.items[0]), [11, 3, 3, 1, 1, 3]);
      await client.query('UPDATE "JewelryItem" SET status=\'SOLD\' WHERE id=$1', [stock]);
      result = await service.summary(user, query);
      assert.deepEqual(counts(result.items[0]), [11, 2, 3, 2, 1, 3]);
      assert.equal(
        result.items[0].total,
        counts(result.items[0])
          .slice(1)
          .reduce((a, b) => a + b, 0),
      );
      const page = await service.summary(user, { branchId, page: 2, pageSize: 1 });
      assert.equal(page.total, 2);
      assert.equal(page.items.length, 1);
      const empty = await service.summary(user, { branchId, page: 99, pageSize: 1 });
      assert.equal(empty.total, 2);
      assert.deepEqual(empty.items, []);
      await client.query('UPDATE "MetalPrice" SET "effectiveFrom"=now()+interval \'1 day\'');
      result = await service.summary(user, query);
      assert.equal(result.items[0].available, 0);
      assert.equal(result.items[0].other, 5);
      await client.query('UPDATE "MetalPrice" SET "effectiveFrom"=now()');
      await client.query('UPDATE "Product" SET "isActive"=false');
      result = await service.summary(user, query);
      assert.equal(result.items[0].available, 0);
      assert.equal(result.items[0].other, 5);
    } finally {
      await client.query('ROLLBACK');
      await client.end();
    }
  },
);

test('ADMIN, assigned MANAGER and STAFF can query; query binds the selected branch', async () => {
  const calls = [];
  const service = new StockService({
    async $queryRaw(query) {
      calls.push(query);
      return [{ items: [], total: 0 }];
    },
  });
  for (const branches of [
    [{ role: 'ADMIN', branchId: null }],
    [{ role: 'MANAGER', branchId }],
    [{ role: 'STAFF', branchId }],
  ]) {
    const result = await service.summary(
      { id: randomUUID(), branches },
      { branchId, page: 1, pageSize: 20 },
    );
    assert.equal(result.total, 0);
    assert.ok(calls.at(-1).values.includes(branchId));
  }
});
